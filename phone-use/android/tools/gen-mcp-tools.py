"""Generate McpTools.java from axdroid.mcp.TOOLS — one source of truth for the
agent-facing tool table, shared by the host MCP server and the on-device one.

Run from phone-use/android:  python tools/gen-mcp-tools.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from axdroid import __version__
from axdroid.mcp import INSTRUCTIONS, PROTOCOLS, TOOLS

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "app", "src", "com", "axuse", "axdroid", "McpTools.java")

tools_json = json.dumps(TOOLS, ensure_ascii=False, indent=0)
instructions = json.dumps(INSTRUCTIONS, ensure_ascii=False)

body = f"""package com.axuse.axdroid;

// GENERATED by tools/gen-mcp-tools.py from axdroid/mcp.py TOOLS — do not edit
// by hand; regenerate after changing the tool table (parity between the host
// MCP server and the on-device one is a product guarantee).

import org.json.JSONArray;
import org.json.JSONObject;

/** The {len(TOOLS)} phone_* tools, byte-identical in schema to the host server. */
final class McpTools {{
    static final String VERSION = "{__version__}";
    static final String[] PROTOCOLS = {{"{PROTOCOLS[0]}", "{PROTOCOLS[1]}", "{PROTOCOLS[2]}"}};
    static final String INSTRUCTIONS = {instructions};

    static JSONArray tools() {{
        try {{
            return new JSONArray(TOOLS_JSON);
        }} catch (Exception e) {{
            return new JSONArray();
        }}
    }}

    static boolean isReadOnly(String name) {{
        try {{
            JSONArray a = tools();
            for (int i = 0; i < a.length(); i++) {{
                JSONObject t = a.getJSONObject(i);
                if (t.optString("name").equals(name))
                    return t.getJSONObject("annotations").optBoolean("readOnlyHint");
            }}
        }} catch (Exception ignored) {{
        }}
        return false;
    }}

    private static final String TOOLS_JSON =
        {chr(34)}\\n{chr(34)}.join(json.dumps(l, ensure_ascii=False) for l in _split_lines(tools_json));
}}

final class Mcp {{
    static final String SERVER_INFO_NAME = "axdroid";
    static final String SERVER_INFO_TITLE = "axuse phone-use (Android, on-device)";
}}
"""


def _split_lines(s: str):
    # emit the JSON as Java string-concat lines, escaping quotes/backslashes
    out = []
    for line in s.splitlines():
        if not line.strip():
            continue
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('"' + esc + '"')
    return out


def _gen() -> str:
    lines = _split_lines(tools_json)
    joined = '\n        + '.join(lines)
    return f"""package com.axuse.axdroid;

// GENERATED by tools/gen-mcp-tools.py from axdroid/mcp.py TOOLS — do not edit
// by hand; regenerate after changing the tool table. Parity between the host
// MCP server and the on-device one is a product guarantee.

import org.json.JSONArray;
import org.json.JSONObject;

import java.util.Locale;

/** The phone_* tools, byte-identical in schema to the host server. */
final class McpTools {{
    static final String VERSION = "{__version__}";
    static final String[] PROTOCOLS = {{"{PROTOCOLS[0]}", "{PROTOCOLS[1]}", "{PROTOCOLS[2]}"}};
    static final String INSTRUCTIONS = {instructions};

    static JSONArray tools() {{
        try {{
            return new JSONArray(TOOLS_JSON);
        }} catch (Exception e) {{
            return new JSONArray();
        }}
    }}

    static boolean isReadOnly(String name) {{
        try {{
            JSONArray a = tools();
            for (int i = 0; i < a.length(); i++) {{
                JSONObject t = a.getJSONObject(i);
                if (t.optString("name").equals(name))
                    return t.getJSONObject("annotations").optBoolean("readOnlyHint");
            }}
        }} catch (Exception ignored) {{
        }}
        return false;
    }}

    private static final String TOOLS_JSON =
        {joined};
}}
"""


if __name__ == "__main__":
    src = _gen()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    n = len(TOOLS)
    print(f"wrote {OUT} ({n} tools, {len(src.splitlines())} lines)")
